CREATE TABLE IF NOT EXISTS sync_job (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_playlist_id TEXT NOT NULL,
    destination_playlist_id TEXT NOT NULL,
    direction TEXT NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_sync_job_relation
    UNIQUE (source_playlist_id, destination_playlist_id, direction)
    );

CREATE TABLE IF NOT EXISTS sync_run (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sync_job_id BIGINT NOT NULL REFERENCES sync_job(id),
    started_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    completed_at TIMESTAMP,
    status VARCHAR(20),
    CONSTRAINT ck_sync_run_status
    CHECK (status IN ('RUNNING', 'SUCCESS', 'FAILED'))
    );

CREATE TABLE IF NOT EXISTS synced_track (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sync_job_id BIGINT NOT NULL REFERENCES sync_job(id),
    source_track_id TEXT NOT NULL,
    source_title TEXT,
    source_artist TEXT,
    destination_track_id TEXT NOT NULL,
    match_confidence REAL,
    status TEXT,
    synced_at TIMESTAMP,
    UNIQUE (sync_job_id, source_track_id)
    );